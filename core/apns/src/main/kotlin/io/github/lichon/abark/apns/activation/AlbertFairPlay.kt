    /** The key as PEM text — the form [DeviceKey] and [FairPlayMaterial] expect. */
    val privateKeyPem: String by lazy {
        Base64.getMimeDecoder().decode(FAIRPLAY_PRIVATE_KEY).toString(Charsets.UTF_8)
    }

    /** Concatenated DER certificates, ready to drop into `FairPlayCertChain` verbatim. */
    val certChainDer: ByteArray by lazy { Base64.getMimeDecoder().decode(FAIRPLAY_CERT_CHAIN) }

    /** The chain split back into certificates: leaf, Apple iPhone Device CA, Apple iPhone CA, Apple Root CA. */
    val certificates: List<X509Certificate> by lazy {
        CertificateFactory.getInstance("X.509")
            .generateCertificates(certChainDer.inputStream())
            .map { it as X509Certificate }
    }

    /** The FairPlay certificate itself — the one whose key signs `ActivationInfoXML`. */
    val leafCertificate: X509Certificate get() = certificates.first()

    /**
     * Credentials for activation: the static chain plus a signer over the static key. Built once and cached — parsing a
     * key and a chain per activation is wasted work on a phone.
     */
    val credentials: FairPlayCredentials by lazy {
        FairPlayCredentials(
            certChainDer = certChainDer,
            signer = RsaFairPlaySigner(DeviceKey.parsePrivateKey(privateKeyPem)),
        )
    }
